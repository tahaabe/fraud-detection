"""Generate sql/04_model_table.sql and the feature list from the EDA decisions."""
import json
from pathlib import Path

VERSION = "v1"
V_KEEP = json.loads(Path("src/features/v_keep_v1.json").read_text())["columns"]
SCHEMAS = Path("sql/schemas")

# 9 near-empty ids (EDA 2d) + id_31 (replaced by browser_family)
DROP_IDS = {"id_07", "id_08", "id_21", "id_22", "id_23", "id_24", "id_25", "id_26", "id_27", "id_31"}

BASE = (
    ["TransactionAmt", "ProductCD", "card1", "card2", "card3", "card4", "card5",
     "addr1", "addr2", "dist1", "dist2", "P_emaildomain", "R_emaildomain"]
    + [f"C{i}" for i in range(1, 15)]
    + [f"D{i}" for i in range(1, 16)]          # raw D kept (normalized D = absolute dates, rejected in 2e)
    + [f"M{i}" for i in range(1, 10)]
    + V_KEEP
    + [f"id_{i:02d}" for i in range(1, 39) if f"id_{i:02d}" not in DROP_IDS]
    + ["DeviceType", "DeviceInfo", "has_identity"]
)
UID = ["uid_txn_no", "uid_secs_since_prev", "uid_cnt_24h", "uid_cnt_7d",
       "uid_amt_mean_past", "uid_amt_std_past", "uid_amt_z", "uid_amt_ratio",
       "uid_n_emails", "uid_n_devices"]
TXN = ["amt_decimals", "hour_rel", "weekday_rel", "card6_clean", "browser_family",
       "email_match", "card1_cnt_30d", "addr1_cnt_30d", "p_email_cnt_30d", "amt_cnt_30d"]

METADATA = ["TransactionID", "transaction_ts", "day", "split", "fold", "uid"]
LABEL = "isFraud"
FEATURES = BASE + UID + TXN


def string_cols(table):
    schema = json.loads((SCHEMAS / f"{table}.json").read_text())
    return {f["name"] for f in schema if f["type"] == "STRING"}


STRING_COLS = string_cols("train_transaction") | string_cols("train_identity") | {"card6_clean", "browser_family"}
CATEGORICAL = [c for c in FEATURES if c in STRING_COLS]


def select_list(alias, cols):
    return ",\n  ".join(f"{alias}.{c}" for c in cols)


SQL = f"""-- GENERATED by src/gcp/build_model_table.py ({VERSION}) - do not edit by hand
CREATE OR REPLACE TABLE fraud_features.model_table_{VERSION}
PARTITION BY TIMESTAMP_TRUNC(transaction_ts, MONTH)
CLUSTER BY fold, ProductCD
AS
SELECT
  c.TransactionID,
  c.transaction_ts,
  c.day,
  c.split,
  CASE
    WHEN c.split = 'test' THEN 'test'
    WHEN c.day <= 30  THEN 'warmup'   -- history only (cold start)
    WHEN c.day <= 122 THEN 'train'
    WHEN c.day <= 152 THEN 'gap'      -- mimics the 30-day deployment delay
    ELSE 'valid'
  END AS fold,
  u.uid,
  c.{LABEL},
  {select_list("c", BASE)},
  {select_list("u", UID)},
  {select_list("t", TXN)}
FROM fraud_clean.transactions AS c
LEFT JOIN fraud_features.uid_features AS u USING (TransactionID)
LEFT JOIN fraud_features.txn_features AS t USING (TransactionID);
"""


def main():
    Path(f"sql/04_model_table.sql").write_text(SQL, encoding="utf-8")
    spec = {"version": VERSION, "label": LABEL, "metadata": METADATA,
            "features": FEATURES, "categorical": CATEGORICAL}
    Path(f"src/features/feature_list_{VERSION}.json").write_text(json.dumps(spec, indent=2))
    print(f"Features: {len(FEATURES)} ({len(CATEGORICAL)} categorical) "
          f"= base {len(BASE)} + uid {len(UID)} + txn {len(TXN)}")
    print("Wrote sql/04_model_table.sql and src/features/feature_list_v1.json")


if __name__ == "__main__":
    main()